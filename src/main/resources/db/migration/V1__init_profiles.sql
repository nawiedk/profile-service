DROP TABLE IF EXISTS project_urls;
DROP TABLE IF EXISTS skill_technologies;
DROP TABLE IF EXISTS profile_projects;
DROP TABLE IF EXISTS profile_skills;
DROP TABLE IF EXISTS projects;
DROP TABLE IF EXISTS skills;
DROP TABLE IF EXISTS profiles;

CREATE TABLE profiles (
                          profile_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                          name VARCHAR(100) NOT NULL,
                          bio VARCHAR(1000),
                          location VARCHAR(255) NOT NULL,
                          role VARCHAR(100) NOT NULL,
                          image_url VARCHAR(500) NOT NULL,
                          github_url VARCHAR(500),
                          linked_In_url VARCHAR(500),
                          profile_status VARCHAR(20) NOT NULL
);

CREATE TABLE skills (
                        skill_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        name VARCHAR(100) NOT NULL UNIQUE,
                        category VARCHAR(50),
                        proficiency_level INT NOT NULL
);

CREATE TABLE projects (
    project_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    preview_text VARCHAR(1000) NOT NULL,
    description VARCHAR(1000)
);

CREATE TABLE profile_skills (
                                profile_id BIGINT NOT NULL,
                                skill_id BIGINT NOT NULL,
                                PRIMARY KEY (profile_id, skill_id),
                                FOREIGN KEY (profile_id) REFERENCES profiles (profile_id),
                                FOREIGN KEY (skill_id) REFERENCES skills (skill_id)
);

CREATE TABLE profile_projects (
    profile_id BIGINT NOT NULL,
    project_id BIGINT NOT NULL,
    PRIMARY KEY (profile_id, project_id),
    FOREIGN KEY (profile_id) REFERENCES profiles (profile_id),
    FOREIGN KEY (project_id) REFERENCES projects (project_id)
);

CREATE TABLE skill_technologies (
    project_id BIGINT NOT NULL,
    skill_id BIGINT NOT NULL,
    PRIMARY KEY (project_id, skill_id),
    FOREIGN KEY (project_id) REFERENCES projects (project_id),
    FOREIGN KEY (skill_id) REFERENCES skills (skill_id)
);

CREATE TABLE project_urls (
    project_id BIGINT NOT NULL,
    url VARCHAR(500) NOT NULL,
    PRIMARY KEY (project_id, url),
    FOREIGN KEY (project_id) REFERENCES projects (project_id)
);

